let n = 0;
export function makeRecord(kind: RecordKind, overrides: Record<string, unknown> = {}): ForgeRecord {
  n += 1;
  const base = {
    id: overrides.id ?? REC(20 + n),
    missionId: MISSION,
    seq: 1,
    kind,
    author: (overrides.author as Author) ?? authorFor[kind],
    ts: TS,
    refs: [] as string[],
    body: bodyFixtures[kind](),
    prevHash: overrides.prevHash ?? HASH_A,
    hash: overrides.hash ?? HASH_B,
  };
  if (overrides.body !== undefined) base.body = overrides.body;
  return base as unknown as ForgeRecord;
}
